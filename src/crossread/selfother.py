"""Self vs other: does a language model predict reading times better on text it generated itself?

EMTeC crosses 3 generators (phi2, mistral = Mistral-7B-Instruct, wizardlm = WizardLM-13B, a
Llama-2-13b fine-tune) with surprisal from ~11 scorer LMs, two of which ARE generators
(phi2, mistral-instruct) and two of which are their relatives (mistral-base, llama2-13b).

Design: Delta-LL[generator g, scorer s] = how much scorer s's surprisal improves a
length/frequency baseline on reading times for texts generated by g.

Self advantage (double difference, paired by item):
    DD(g, s) = [dLL(g, s) - dLL(g', s)] - mean_X [dLL(g, X) - dLL(g', X)]
i.e. how much more scorer s gains on g's texts than on another generator g''s texts,
beyond what an unrelated reference scorer X gains on the same two text sets. This removes
(a) scorer quality and (b) text-set difficulty, leaving the scorer x generator interaction.
Uncertainty: item bootstrap (items are shared across generators, so resampling is paired),
computed from per-item sufficient statistics so thousands of reps are cheap.
"""
from __future__ import annotations

import re
import warnings

import numpy as np
import pandas as pd

warnings.filterwarnings("ignore", message=".*encountered in matmul")

GENERATORS = ["phi2", "mistral", "wizardlm"]
RELATION = {  # (generator, scorer) -> relation; everything else is "other"
    ("phi2", "phi2"): "self",
    ("mistral", "mistral-instruct"): "self",
    ("mistral", "mistral-base"): "base",
    ("wizardlm", "llama2-13b"): "base",
    ("wizardlm", "llama2-7b"): "family",  # same pretraining data/tokenizer as WizardLM's base
}
PUNCT = re.compile(r"[^\w]", re.UNICODE)
MEASURES = {"FFD": "FFD", "GD": "FPRT", "TFT": "TFT"}


def scorer_columns(cols):
    """{(scorer, variant): column}. variant 'text' = surprisal_<lm>, 'prompt' = surprisal_p_<lm>."""
    out = {}
    for c in cols:
        if c.startswith("surprisal_p_"):
            out[(c[len("surprisal_p_"):], "prompt")] = c
        elif c.startswith("surprisal_"):
            out[(c[len("surprisal_"):], "text")] = c
    return out


def related_scorers():
    return {s for (_, s) in RELATION}


def word_table(rm: pd.DataFrame, min_readers: int = 3) -> tuple[pd.DataFrame, dict]:
    """Reader-averaged word table with predictors and previous-word (spillover) predictors."""
    scols = scorer_columns(rm.columns)
    keys = ["item_id", "model", "decoding_strategy", "word_id"]
    rm = rm.copy()
    for raw in MEASURES.values():
        rm[raw] = pd.to_numeric(rm[raw], errors="coerce")
        rm.loc[rm[raw] <= 0, raw] = np.nan  # EMTeC codes "not fixated" as 0
    static = ["word", "word_length_without_punct", "zipf_freq", "task"] + list(scols.values())
    w = rm.groupby(keys).agg(**{m: (raw, "mean") for m, raw in MEASURES.items()},
                             n_readers=("subject_id", "nunique"),
                             **{c: (c, "first") for c in static}).reset_index()
    w = w.sort_values(keys)
    w["text_id"] = w["item_id"] + "|" + w["model"] + "|" + w["decoding_strategy"]
    g = w.groupby("text_id")
    w["length"] = w["word_length_without_punct"].astype(float)
    w["zipf"] = w["zipf_freq"].astype(float)
    for c in ["length", "zipf"] + list(scols.values()):
        w[f"prev_{c}"] = g[c].shift(1)
    first, last = g.cumcount() == 0, g.cumcount(ascending=False) == 0
    has_punct = w["word"].astype(str).str.replace(PUNCT, "", regex=True) != w["word"].astype(str)
    keep = ~first & ~last & ~has_punct & (w["n_readers"] >= min_readers)
    return w[keep].reset_index(drop=True), scols


# --------------------------------------------------------------------- sufficient statistics
def _design(d, scol=None):
    cols = [np.ones(len(d)), d["length"], d["zipf"], d["length"] * d["zipf"],
            d["prev_length"], d["prev_zipf"], d["prev_length"] * d["prev_zipf"]]
    if scol is not None:
        cols += [d[scol], d[f"prev_{scol}"]]
    return np.column_stack([np.asarray(c, float) for c in cols])


def item_stats(d, measure, scol, items):
    """Per-item X'X, X'y, y'y, n for baseline and full model, on a common row set."""
    need = [measure, "length", "zipf", "prev_length", "prev_zipf", scol, f"prev_{scol}"]
    d = d.dropna(subset=need)
    idx = pd.Index(items).get_indexer(d["item_id"])
    y = d[measure].to_numpy(float)
    out = {}
    for name, X in [("base", _design(d)), ("full", _design(d, scol))]:
        k = X.shape[1]
        XtX = np.zeros((len(items), k, k))
        Xty = np.zeros((len(items), k))
        np.add.at(XtX, idx, X[:, :, None] * X[:, None, :])
        np.add.at(Xty, idx, X * y[:, None])
        out[name] = (XtX, Xty)
    yty = np.zeros(len(items))
    n = np.zeros(len(items))
    np.add.at(yty, idx, y * y)
    np.add.at(n, idx, 1)
    return out, yty, n


def dll_from_stats(stats, w):
    """Per-word in-sample Delta-LL (nats) of full over base, with item weights w (bootstrap counts)."""
    (st, yty, n) = stats
    N = w @ n
    rss = {}
    for name, (XtX, Xty) in st.items():
        A = np.tensordot(w, XtX, 1)
        b = w @ Xty
        beta = np.linalg.lstsq(A, b, rcond=None)[0]
        rss[name] = w @ yty - beta @ b
    return 0.5 * np.log(rss["base"] / rss["full"]), N


# --------------------------------------------------------------------- main analyses
def run(w: pd.DataFrame, scols: dict, measures=("FFD", "GD", "TFT"), variant="prompt",
        n_boot=2000, seed=0, by_decoding=True):
    rng = np.random.default_rng(seed)
    scorers = sorted({s for (s, v) in scols if v == variant})
    refs = [s for s in scorers if s not in related_scorers()]
    gens = [g for g in GENERATORS if g in set(w["model"])]
    items = sorted(w["item_id"].unique())

    def compute(sub, gs):
        return {(m, g, s): item_stats(sub[sub.model == g], m, scols[(s, variant)], items)
                for m in measures for g in gs for s in scorers}

    def matrix(S, wts):
        return {k: dll_from_stats(v, wts)[0] for k, v in S.items()}

    def dd_table(D, m, gens):
        rows = []
        for g in gens:
            for s in scorers:
                rel = RELATION.get((g, s))
                if rel is None:
                    continue
                vals = []
                for g2 in gens:
                    if g2 == g:
                        continue
                    ref = np.mean([D[(m, g, x)] - D[(m, g2, x)] for x in refs])
                    vals.append((D[(m, g, s)] - D[(m, g2, s)]) - ref)
                rows.append(dict(measure=m, generator=g, scorer=s, relation=rel, DD=np.mean(vals)))
        return rows

    def analyse(sub, label):
        gs = [g for g in gens if g in set(sub["model"])]
        S = compute(sub, gs)
        ones = np.ones(len(items))
        D0 = matrix(S, ones)
        point = pd.DataFrame([r for m in measures for r in dd_table(D0, m, gs)])
        boots = []
        for _ in range(n_boot):
            wts = np.bincount(rng.integers(0, len(items), len(items)), minlength=len(items)).astype(float)
            Db = matrix(S, wts)
            boots.append([r["DD"] for m in measures for r in dd_table(Db, m, gs)])
        boots = np.array(boots)
        point["ci_lo"], point["ci_hi"] = np.percentile(boots, [2.5, 97.5], axis=0)
        point["p_boot"] = [min(1.0, max(1 / n_boot, 2 * min((b <= 0).mean(), (b >= 0).mean())))
                           for b in boots.T]
        point["subset"] = label
        mat = pd.DataFrame([dict(measure=m, generator=g, scorer=s, variant=variant,
                                 relation=RELATION.get((g, s), "other"), dLL=D0[(m, g, s)],
                                 n_words=dll_from_stats(S[(m, g, s)], ones)[1], subset=label)
                            for (m, g, s) in D0])
        return point, mat

    print(f"  scorers ({variant}): {scorers}\n  reference scorers: {refs}")
    dd, mat = analyse(w, "all")
    dd_dec, mat_dec = [], []
    if by_decoding:
        for dec, sub in w.groupby("decoding_strategy"):
            if sub["model"].nunique() < 2:
                continue
            p, mm = analyse(sub, dec)
            dd_dec.append(p)
            mat_dec.append(mm)
    dd_dec = pd.concat(dd_dec, ignore_index=True) if dd_dec else pd.DataFrame()
    mat_dec = pd.concat(mat_dec, ignore_index=True) if mat_dec else pd.DataFrame()
    return dd, mat, dd_dec, mat_dec


def mean_surprisal_matrix(w, scols, variant="prompt"):
    rows = []
    for (s, v), c in scols.items():
        if v != variant:
            continue
        for g, sub in w.groupby("model"):
            rows.append(dict(generator=g, scorer=s, variant=v,
                             relation=RELATION.get((g, s), "other"),
                             mean_surprisal=sub[c].mean(), sd_surprisal=sub[c].std()))
    return pd.DataFrame(rows)


def plot_matrix(mat, path, measure):
    import matplotlib.pyplot as plt

    m = mat[mat.measure == measure].pivot(index="generator", columns="scorer", values="dLL")
    # center each scorer column so the colour shows the scorer x generator interaction
    mc = m - m.mean(axis=0)
    fig, ax = plt.subplots(figsize=(1.0 + 0.75 * m.shape[1], 2.8))
    lim = np.nanmax(np.abs(mc.values))
    im = ax.imshow(mc.values, cmap="RdBu_r", vmin=-lim, vmax=lim, aspect="auto")
    ax.set_xticks(range(m.shape[1]), m.columns, rotation=45, ha="right")
    ax.set_yticks(range(m.shape[0]), [f"{g} texts" for g in m.index])
    for i, g in enumerate(m.index):
        for j, s in enumerate(m.columns):
            rel = RELATION.get((g, s))
            ax.text(j, i, f"{1000 * m.iloc[i, j]:.1f}" + ("*" if rel == "self" else "+" if rel else ""),
                    ha="center", va="center", fontsize=7)
    ax.set_title(f"{measure}: dLL x1000 (colour = centred within scorer; * self, + base model)", fontsize=8)
    fig.colorbar(im, ax=ax, fraction=0.03)
    fig.tight_layout()
    fig.savefig(path, dpi=140)
    plt.close(fig)
